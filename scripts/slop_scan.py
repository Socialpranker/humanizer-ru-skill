def layout_flags(text, words, reference=False, markup=None):
    """Приметы компоновки. text — после mask_foreign. reference: справочник с кодом, где заголовки и перечни ярлыков — норма.
    markup: Doc.layout из HTML, то есть блок под заголовком, карточки и полосы, которых в тексте не видно."""
    markup = markup or {}
    lines = [ln for ln in text.split("\n") if ln.strip()]
    if lines and lines[0].strip() == "---" and "---" in [ln.strip() for ln in lines[1:40]]:
        lines = lines[[ln.strip() for ln in lines[1:40]].index("---") + 2 :]
    lines = [ln for ln in lines if not ln.lstrip().startswith("|")]
    if not lines:
        return []

    def head_of(ln):
        m = MD_HEAD.match(ln) or BOLD_HEAD.match(ln)
        return m.group(1).strip(" *_#:") if m else None

    out = []
    first = lines[0]
    n_first = len(WORD.findall(first))
    titled = head_of(first) is not None or (n_first <= 12 and first.rstrip()[-1] not in ".!?:;,…")
    hero = []
    if markup.get("hero"):
        hero.append("блок под заголовком в разметке: " + ", ".join(markup["hero"]))
    if titled:
        for ln in [x for x in lines[1:4] if head_of(x) is None]:
            n = len(WORD.findall(ln))
            if META_LINE.match(ln):
                hero.append("строка «Дата/Автор/Статус:»")
            # до 5 слов: «Аня берёт интеграцию с amoCRM. Срок 12 декабря.» в записке Haiku (этап 6) шапкой не является
            elif n <= 5 and DATE_RX.search(ln):
                hero.append("строка с датой")
            elif ITALIC_LINE.match(ln) and n <= 25:
                hero.append("строка-описание курсивом")
    if hero:
        out.append(
            f"вид: шапка под заголовком ({', '.join(dict.fromkeys(hero))}). Убери её и начни с абзаца по делу; "
            "дату, если она нужна читателю, назови в тексте"
        )
    if not reference and markup.get("blocks", 0) + markup.get("stripes", 0) >= 3:
        out.append(
            f"вид: карточек и плашек {markup.get('blocks', 0)}, полос слева {markup.get('stripes', 0)}. "
            "Пиши абзацами и отделяй блоки отступом"
        )
    heads = [h for h in map(head_of, lines) if h is not None]
    boiler = [h for h in heads if BOILER_HEAD.match(h)]
    if boiler:
        out.append(
            f"вид: шаблонные разделы «{'», «'.join(dict.fromkeys(boiler))}». Главное скажи в первом абзаце, "
            "а раздел назови по содержанию или убери"
        )
    if not reference and len(heads) >= 3 and len(heads) / max(words, 1) * 1000 > 6:
        out.append(
            f"вид: заголовков {len(heads)} на {words} слов. Письмо и записка до страницы идут без заголовков, "
            "в длинном документе хватает одного на экран"
        )
    body = [ln for ln in lines if head_of(ln) is None]
    if not reference:
        # Контроль на людях (Habr, layout_check.py пилота): без этих границ флаг ловил обычные фразы с тире
        # в начале («Shadow DOM – штука не новая…»). Ярлык — короткая строка, пункт списка или зачин в одно слово.
        labels = [
            ln.strip()
            for ln in body
            if LABEL_LINE.match(ln)
            and (LIST_LINE.match(ln) or len(WORD.findall(ln)) <= 14 or LABEL_OPENER.match(ln))
        ]
        if len(labels) >= 3:
            out.append(
                f"вид: строк-ярлыков «Слово: пояснение» {len(labels)} (например «{labels[0][:50]}»). "
                "Пиши предложением с глаголом"
            )
        bold_lead = sum(1 for ln in body if BOLD_LEAD.match(ln))
        if bold_lead >= 3:
            out.append(f"вид: пунктов с жирным началом {bold_lead}. Сними жирный и начни пункт с сути")
        bold = sum(len(BOLD_SPAN.findall(ln)) for ln in body)
        if bold >= 4 and bold > bold_lead:
            out.append(f"вид: жирных выделений {bold}. Оставь не больше одного на документ")
    paras = []
    for p in re.split(r"\n\s*\n", text):
        kept = [ln for ln in p.split("\n") if ln.strip() and head_of(ln) is None and not ln.lstrip().startswith("|")]
        if kept:
            paras.append(" ".join(ln.strip() for ln in kept))
    if len(paras) >= 3:
        last = paras[-1]
        if ECHO_END.match(last):
            out.append(
                f"вид: концовка-повтор («{last[:40].strip()}…»). В конце пиши только новое: что сделать, кому и к какому сроку"
            )
        m = DOC_OPEN.search(paras[0][:300])
        if m:
            out.append(f"вид: вступление о самом документе («{m.group(0)}»). Начни с главного факта или решения")
    return out


def blank(s):
    return re.sub(r"[^\n]", GAP, s)


def mask_foreign(text):
    """Код и цитаты не сканируем: длина строк сохраняется, номера строк не плывут."""
    out, in_fence, fence_ch, quoting = [], False, "", False
    for line in text.split("\n"):
        m = FENCE.match(line)
        if in_fence:
            out.append(blank(line))
            if m and m.group(1)[0] == fence_ch and not line.strip(fence_ch):
                in_fence = False
            continue
        if m:
            in_fence, fence_ch = True, m.group(1)[0]
            out.append(blank(line))
            continue
        if line.lstrip().startswith(">"):
            quoting = True
            out.append(blank(line))
            continue
        if (
            quoting
            and line.strip()
            and not re.match(r"^\s*(#|[-*+]\s|\d+[.)]\s)", line)
        ):
            out.append(blank(line))
            continue
        quoting = False
        out.append(INLINE_CODE.sub(lambda mm: blank(mm.group(0)), line))
    masked = "\n".join(out)
    return SHORT_QUOTE.sub(lambda mm: blank(mm.group(0)), masked)


def line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def split_sentences(text):
    sents = []
    for para in re.split(r"\n\s*\n", text):
        for line in para.split("\n"):
            if (
                not line.strip()
                or LIST_LINE.match(line)
                or line.lstrip().startswith("#")
            ):
                continue
            sents.extend(s.strip() for s in SENT_END.split(line) if s.strip())
    return sents


def paragraphs(text):
    pos = 0
    for chunk in re.split(r"(\n\s*\n)", text):
        if chunk.strip() and not re.fullmatch(r"\n\s*\n", chunk):
            yield pos, chunk
        pos += len(chunk)


def staccato_runs(sents):
    runs, cur = [], 0
    for s in sents:
        n = len(WORD.findall(s))
        if 0 < n <= 3 and s[-1] not in "?!:;":
            cur += 1
        else:
            if cur >= 3:
                runs.append(cur)
            cur = 0
    if cur >= 3:
        runs.append(cur)
    return runs


ABBR = re.compile(r"(?<![\w-])(?:мин|опт|прод|макс|мес|доп|кол-во)\.?(?![\w-])", re.IGNORECASE)

# Английский в русской прозе допустим только как термин или название (RAG, Claude, numpy). Лексически
# термин от бытового слова не отличить, поэтому ловим бытовые слова из списка и английские обороты
# со служебными словами. Аббревиатуры, имена с заглавной, слова в скобках и после «от английского»,
# «или», «называют» — пояснения термина, их не считаем.
EN_EVERYDAY = frozenset(
    "vs via per etc ok okay done todo fix fixed check checked run runs read write file files name names "
    "purpose params param defs def call calls result results tool tools drop store clear cap hard soft "
    "latency summary summaries payback lifetime input output default fallback scope tradeoff trade-off "
    "insight insights feedback flow step steps next prev item items list issue issues task tasks stuff "
    "thing things note notes hint hints draft final total before after start end fast slow cheap big "
    "small new old good bad high low main core key value values".split()
)
EN_FUNC = frozenset("the of and to for with is are was be by from in on at or not as an a".split())
EN_RUN = re.compile(r"(?<![\w./\\@#-])[a-z][a-z'-]*(?:[ \t]+[a-z][a-z'-]*)*(?![\w/\\(@-]|\.\w)")
EN_GLOSS = re.compile(r"(?:\bот(?:\s+англ\w*)?|\bили|по-английски|англ\.|называ\w+|термин)\s*$", re.IGNORECASE)
PARENS = re.compile(r"\([^()\n]*\)")
CYR = re.compile(r"[а-яё]", re.IGNORECASE)


def english_mix(text):
    """Бытовые английские слова и обороты внутри русских абзацев: [фрагмент]."""
    t = PARENS.sub(lambda m: blank(m.group(0)), re.sub(r"https?://\S+", lambda m: blank(m.group(0)), text))
    out = []
    for start, chunk in paragraphs(t):
        words = WORD.findall(chunk)
        if not words or sum(bool(CYR.search(w)) for w in words) * 2 < len(words):
            continue  # английский абзац (аннотация, цитата) целиком: это не смесь
        for m in EN_RUN.finditer(chunk):
            ws = m.group(0).split()
            if len(ws) > 4 or EN_GLOSS.search(chunk[max(0, m.start() - 25) : m.start()]):
                continue  # длинный оборот — цитата, а не вкрапление
            if any(w in EN_EVERYDAY for w in ws) or (len(ws) >= 2 and any(w in EN_FUNC for w in ws)):
                out.append(m.group(0))
    return out

