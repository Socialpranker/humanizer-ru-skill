def dash_allowance(words, foreign=False):
    # свой текст: тире нет совсем (читатели узнают по нему ИИ, и одно тире в коротком письме заметно);
    # чужой текст на правке: одно на 200 слов, чтобы не вычищать голос автора
    return max(1, words // 200) if foreign else 0


# Двоеточие в середине фразы: перед ним во фразе три слова и больше, после него слово с маленькой буквы.
# Время, ссылки, «Тема: План» и ярлык в одно-два слова («Первый: …») сюда не попадают.
MID_COLON = re.compile(r"(?<=[A-Za-zА-Яа-яЁё»\")])\s?:[ \t]+(?=[а-яё])")


def colon_allowance(words, foreign=False):
    # Замер 23.11.2026 (research/humanlikeness/live/colon_check.py): под запретом тире модель ставит двоеточие,
    # 80–110 на 10 тыс. слов против 28 в постах людей и 28 в сыром тексте модели, где тире разрешено.
    # Свой текст: одно на 200 слов (медиана поста человека одно на 400). Чужой на правке: одно на 100 слов,
    # это выше p90 постов людей (7,9 на 1000 слов), чтобы не вычищать голос автора.
    return max(1, words // (100 if foreign else 200))


def mid_colons(sents):
    found = []
    for sent in sents:
        for part in sent.split("\n"):
            for m in MID_COLON.finditer(part):
                if len(WORD.findall(part[: m.start()])) >= 3:
                    found.append(part.strip())
    return found


