    r"\b(?:в (?:этой|данной|настоящей) (?:записке|справке|статье|заметке)|в (?:этом|данном|настоящем) (?:документе|письме|отч[её]те|обзоре)|"
    r"ниже (?:я |мы )?(?:\w+ ){0,2}(?:разбер|рассмотр|привед|опис|изложен)|(?:этот|данный|настоящий) документ|"
