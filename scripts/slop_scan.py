def _xml_paragraphs(data, para_tag, text_tag):
    out = []
    for para in re.findall(rf"<{para_tag}[ >].*?</{para_tag}>", data, re.S):
        t = "".join(re.findall(rf"<{text_tag}(?: [^>]*)?>([^<]*)</{text_tag}>", para))
        if t.strip():
            out.append(html.unescape(t.strip()))
    return out


HTML_DROP = re.compile(r"<(script|style|svg|template|noscript)\b.*?</\1\s*>|<!--.*?-->", re.S | re.I)
HTML_BLOCK = re.compile(
    r"</?(?:p|div|section|article|header|footer|main|aside|h[1-6]|li|ul|ol|tr|table|blockquote|figcaption|br|hr)\b[^>]*>",
    re.I,
)
# Колода: элементы с классом ровно `slide` или reveal.js (<section> внутри .slides). Голые <section>
# не в счёт: так свёрстаны обычные отчёты и лендинги, а в режиме слайдов отключаются проверки прозы.
HTML_CLASSED = re.compile(r"<(?:section|div)\b[^>]*\bclass=[\"']([^\"']*)[\"'][^>]*>", re.I)
HTML_SECTION = re.compile(r"<section\b[^>]*>", re.I)


def _slide_cuts(data):
    classed = [(m.start(), m.group(1).split()) for m in HTML_CLASSED.finditer(data)]
    cuts = [pos for pos, cls in classed if "slide" in cls]
    if not cuts and any("slides" in cls for _pos, cls in classed):
        cuts = [m.start() for m in HTML_SECTION.finditer(data)]
    return cuts


HTML_HEAD = re.compile(r"<h([1-6])\b[^>]*>(.*?)</h\1\s*>", re.S | re.I)
HTML_LI = re.compile(r"<li\b[^>]*>", re.I)
CLASS_ATTR = re.compile(r"\bclass=[\"']([^\"']*)[\"']", re.I)
HERO_CLASS = {"subtitle", "lead", "tagline", "byline", "date", "meta", "kicker", "eyebrow", "chip", "badge"}
BLOCK_CLASS = {"card", "badge", "chip", "pill", "tag", "callout", "box", "note", "tile", "kpi"}


class Doc(str):
    """Текст документа плюс то, что видно только в разметке (блок под заголовком, карточки, полосы слева)."""

    layout = None


def _html_layout(data):
    body = HTML_DROP.sub(" ", data)
    m = re.search(r"</h1\s*>", body, re.I)
    after = re.split(r"<h[1-6]\b", body[m.end() : m.end() + 800], flags=re.I)[0] if m else ""
    hero = list(dict.fromkeys(c for attr in CLASS_ATTR.findall(after) for c in attr.split() if c in HERO_CLASS))
    # страница-приложение (форма, поля, кнопки): карточки там часть интерфейса, а не оформление документа
    app = bool(re.search(r"<(?:form|input|textarea|select)\b", body, re.I)) or len(re.findall(r"<button\b", body, re.I)) >= 3
    blocks = sum(1 for attr in CLASS_ATTR.findall(body) if set(attr.split()) & BLOCK_CLASS)
    stripes = len(re.findall(r"border-left\s*:\s*\d", data, re.I))
    return {"hero": hero, "blocks": 0 if app else blocks, "stripes": 0 if app else stripes}


def _html_head(m):
    title = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", m.group(2))).strip()
    return f"\n\n{'#' * min(int(m.group(1)), 3)} {title}\n\n" if title else "\n\n"


def _html_text(data):
    """HTML -> текст абзацами: без script/style/svg и тегов, иначе латиница разметки топит кириллицу.
    Заголовки и пункты списков остаются в разметке markdown, чтобы слой вида видел их так же, как в .md."""
    layout = _html_layout(data)
    data = HTML_LI.sub("\n\n- ", HTML_HEAD.sub(_html_head, HTML_DROP.sub(" ", data)))
    data = HTML_BLOCK.sub("\n\n", data)
    data = re.sub(r"</(b|span|small|strong|em)>(?=[<\w])", r"</\1> ", data)
    data = html.unescape(re.sub(r"<[^>]+>", "", data))
    paras = [re.sub(r"[ \t\r\f\v]+", " ", p).strip() for p in re.split(r"\n\s*\n", data)]
    out = Doc("\n\n".join(p for p in paras if p and p != "-"))
    out.layout = layout
    return out


DOCX_STYLE = re.compile(r'<w:pStyle w:val="([^"]+)"')


def _docx_text(data):
    """Абзацы docx; стиль Title/Heading даёт заголовок markdown, стиль списка даёт пункт."""
    out = []
    for para in re.findall(r"<w:p[ >].*?</w:p>", data, re.S):
        t = html.unescape("".join(re.findall(r"<w:t(?: [^>]*)?>([^<]*)</w:t>", para))).strip()
        if not t:
            continue
        m = DOCX_STYLE.search(para)
        style = m.group(1) if m else ""
        level = re.fullmatch(r"(?:Heading|Заголовок)\s?(\d)", style, re.I)
        if style.lower() == "title" or (level and level.group(1) == "1"):
            t = "# " + t
        elif level:
            t = ("## " if level.group(1) == "2" else "### ") + t
        elif re.match(r"List|Compact", style, re.I):
            t = "- " + t
        out.append(t)
    return "\n\n".join(out)


def _html_slides(data):
    """HTML-колода -> [(заголовок, [строки тела])]; колодой считаем 3+ .slide или <section> reveal.js."""
    data = HTML_DROP.sub(" ", data)
    cuts = _slide_cuts(data)
    if len(cuts) < 3:
        return None
    slides = []
    for a, b in zip(cuts, cuts[1:] + [len(data)]):
        chunk = data[a:b]
        head = re.search(r"<h[1-3]\b[^>]*>(.*?)</h[1-3]\s*>", chunk, re.S | re.I)
        title = _html_text(head.group(1)).replace("\n", " ") if head else ""
        if head:
            chunk = chunk[: head.start()] + chunk[head.end() :]
        body = [ln for ln in _html_text(chunk).split("\n\n") if ln]
        if not title and body:
            title, body = body[0], body[1:]
        if title:
            slides.append((title, body))
    return slides if len(slides) >= 3 else None


def read_slides(path):
    """pptx или HTML-колода -> [(заголовок, [строки тела])]; для HTML без слайдов — None."""
    if path.lower().endswith((".html", ".htm")):
        return _html_slides(open(path, encoding="utf-8", errors="ignore").read())
    slides = []
    with zipfile.ZipFile(path) as z:
        names = sorted(
            (n for n in z.namelist() if re.fullmatch(r"ppt/slides/slide\d+\.xml", n)),
            key=lambda n: int(re.search(r"\d+", n).group()),
        )
        for n in names:
            paras = _xml_paragraphs(z.read(n).decode("utf-8", "ignore"), "a:p", "a:t")
            if paras:
                slides.append((paras[0], paras[1:]))
    return slides


def slides_of(path):
    return read_slides(path) if path.lower().endswith((".pptx", ".html", ".htm")) else None


def read(path):
    if path == "-":
        return sys.stdin.read()
    low = path.lower()
    if low.endswith(".docx"):
        with zipfile.ZipFile(path) as z:
            data = z.read("word/document.xml").decode("utf-8", "ignore")
        return _docx_text(data)
    if low.endswith(".pptx"):
        return "\n\n".join(
            "# " + t + "\n\n" + "\n".join("- " + b for b in body)
            for t, body in read_slides(path)
        )
    if low.endswith((".html", ".htm")):
        return _html_text(open(path, encoding="utf-8", errors="ignore").read())
    if low.endswith(".pdf"):
        # pdftotext из poppler (brew install poppler); без него PDF не читается и сканер падает с ошибкой
        import subprocess

        out = subprocess.run(["pdftotext", "-enc", "UTF-8", path, "-"], capture_output=True, timeout=60, check=True).stdout
        # pdftotext переносит строки по ширине страницы; без склейки каждая строка выглядит обрывком фразы
        paras = re.split(r"\n\s*\n", out.decode("utf-8", "ignore").replace("\f", "\n\n"))
        return "\n\n".join(re.sub(r"\s*\n\s*", " ", p).strip() for p in paras if p.strip())
    return open(path, encoding="utf-8").read()


VERBISH = re.compile(
    r"\d|\b\w+(?:ет|ёт|ут|ют|ит|ат|ят|ал|ала|али|ил|ила|или|ился|илась|ется|ются|ем|им|ла|ло|ли)\b"
    r"|\b(?:нет|есть|не)\b|[—–:]",
    re.IGNORECASE,
)


def slide_flags(slides):
    """Слайды: ритм бессмысленен, смотрим заголовки-темы, триады и перегруз."""
    flags = []
    if len(slides) < 3:
        return flags
    inner = slides[1:]
    topic = [t for t, _ in inner if len(WORD.findall(t)) <= 4 and not VERBISH.search(t)]
    if len(topic) / len(inner) > 0.5:
        flags.append(
            f"заголовки-темы вместо тезисов: {len(topic)} из {len(inner)} "
            f"(«{topic[0]}»; нужен вывод слайда: «Выручка выросла на 12%»)"
        )
    with_body = [b for _, b in inner if len(b) >= 2]
    triads = sum(1 for b in with_body if len(b) == 3)
    if len(with_body) >= 4 and triads / len(with_body) > 0.5:
        flags.append(f"триады: ровно 3 пункта на {triads} из {len(with_body)} слайдов")
    heavy = sum(1 for _, b in inner if sum(len(WORD.findall(x)) for x in b) > 60)
    if heavy:
        flags.append(f"перегруженные слайды (>60 слов в теле): {heavy}")
    colon = sum(1 for _, b in inner for x in b if re.match(r"^[^:]{3,30}:\s+\S", x))
    if colon >= 4:
        flags.append(f"пункты вида «Термин: пояснение»: {colon}")
    return flags


