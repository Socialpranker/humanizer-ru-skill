        raw_b, raw_c = read(a.compare[0]), read(a.compare[1])
        b, c = scan(raw_b, a.genre, slides_of(a.compare[0]), a.foreign), scan(raw_c, a.genre, slides_of(a.compare[1]), a.foreign)
