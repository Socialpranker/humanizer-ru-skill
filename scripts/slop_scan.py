STEM = re.compile(r"[а-яёa-z0-9]{4,}", re.IGNORECASE)


def prose_paragraphs(text):
    """[(строка, [предложения])] только по абзацам прозы: списки, заголовки и таблицы не считаем."""
    out = []
    for start, chunk in paragraphs(text):
        lines = [ln for ln in chunk.split("\n") if ln.strip()]
        if any(LIST_LINE.match(ln) or ln.lstrip().startswith(("#", "|")) for ln in lines):
            continue
        joined = " ".join(ln.strip() for ln in lines)
        sents = [s.strip() for s in SENT_END.split(joined) if len(WORD.findall(s)) >= 2]
        if sents:
            out.append((line_of(text, start), sents))
    return out


def _linked(prev, cur):
    words = WORD.findall(cur)
    if LINK_START.match(" ".join(words[:3])) or ANAPHOR.search(" ".join(words[:6])):
        return True
    if words and PREDICATE.fullmatch(words[0]):
        return True
    stems = lambda s: {w.lower()[:5] for w in STEM.findall(s)}
    return bool(stems(prev) & stems(cur))


def unlinked_pairs(paras):
    """Пары соседних предложений (оба от 4 слов) без связки, отсылки и общего корня: (всего пар, [(строка, A, B)])."""
    total, bad = 0, []
    for line, sents in paras:
        for a, b in zip(sents, sents[1:]):
            if len(WORD.findall(a)) < 4 or len(WORD.findall(b)) < 4:
                continue
            total += 1
            if not _linked(a, b):
                bad.append((line, a, b))
    return total, bad


def verbless(paras):
    """Законченные предложения от 4 слов без сказуемого и без тире-связки: «Стойка жидкостная.»"""
    full = [s for _l, sents in paras for s in sents if len(WORD.findall(s)) >= 4 and s.rstrip().endswith(".")]
    return full, [s for s in full if not PREDICATE.search(s) and not re.search(r"\s[—–:]\s?", s)]


def fragments(text):
    """Обрубки: строка с маленькой буквы или без точки с запятыми внутри («все графы, указан способ, анонс до приёма»)."""
    out = []
    for ln in text.split("\n"):
        ln = ln.strip()
        if not ln or ln.startswith(("#", "|")):
            continue
        ln = re.sub(r"^(?:[-*•]|\d+[.)])\s+", "", ln)
        if len(WORD.findall(ln)) < 4:
            continue
        words = WORD.findall(ln)
        glued_title = ln[:1].islower() and len(words) > 1 and words[1][:1].isupper()
        if (ln[:1].islower() and not glued_title) or (
            ln[-1] not in '.!?…:»)"' and len(WORD.findall(ln)) >= 5 and "," in ln
        ):
            out.append(ln)
    return out


def scan(raw, genre=None, slides=None, foreign=False):
    text = mask_foreign(raw)
    words = len(WORD.findall(text))
    hits = []
    for cat, label, rx in MARKERS:
        for m in re.finditer(rx, text, re.IGNORECASE | re.MULTILINE):
            hits.append(
                {
                    "cat": cat,
                    "label": label,
                    "pos": m.start(),
                    "line": line_of(text, m.start()),
                    "text": re.sub(r"\s+", " ", m.group(0)).strip(),
                }
            )
    muted_c = GENRE_MUTED_CATS.get(genre, set())
    muted_l = GENRE_MUTED_LABELS.get(genre, set())
    hits = [h for h in hits if h["cat"] not in muted_c and h["label"] not in muted_l]
    if foreign:
        hits = [h for h in hits if h["label"] != REVERSE_LABEL]
    hits.sort(key=lambda h: h["pos"])

    clusters = []
    for start, chunk in paragraphs(text):
        end = start + len(chunk)
        inside = [h for h in hits if start <= h["pos"] < end]
        if len(inside) >= 3:
            clusters.append(
                {
                    "line": line_of(text, start),
                    "count": len(inside),
                    "labels": sorted({h["label"] for h in inside}),
                }
            )

    sents = split_sentences(text)
    lengths = [len(WORD.findall(s)) for s in sents if WORD.findall(s)]
    sigma = statistics.pstdev(lengths) if len(lengths) >= 2 else None
    dashes = len(DASH.findall(text))
    lines = [ln for ln in text.split("\n") if ln.strip()]
    items = sum(1 for ln in lines if LIST_LINE.match(ln))
    nominal = len(NOMINAL.findall(text))
    per100 = lambda n: (n / words * 100) if words else 0.0

    flags = []
    if slides is not None:
        flags.extend(slide_flags(slides))
    frags = fragments(text)
    if frags:
        flags.append(
            f"обрубки без законченной фразы: {len(frags)} (например «{frags[0][:60]}»). "
            "Читатель-новичок их не разворачивает: пиши предложением с подлежащим и глаголом"
        )
    abbr = sorted({m.group(0).lower().rstrip(".") for m in ABBR.finditer(text)})
    if abbr:
        flags.append(f"сокращения без расшифровки: {', '.join(abbr)}. Пиши слово целиком")
    # «→», «·», «~12%» вместо слов: у людей 0–4% текстов, в документах Claude для автора 37–53% (patterns.md)
    glyphs = GLYPHS.findall(text)
    if len(glyphs) >= 3:
        flags.append(
            f"значки вместо слов (→, ·, ~число): {len(glyphs)}. Пиши «стало», «около», связывай фразой"
        )
    # калибровка 18.11.2026 (research/clarity/analysis.md): 6+ вкраплений
    # у людей в 0 из 320 текстов (Habr, КиберЛенинка, Lenta, ИНИОН; максимум 5, ключевые слова кода на Habr)
    # и в 0 из 240 текстов модели; у стиля рабочих заметок Claude 6 и 25. Запас у второго нулевой.
    # Автор назвал «перемешку английского» причиной непонятности такого текста.
    english = english_mix(text)
    if len(english) >= 6:
        flags.append(
            f"английские слова вместо русских: {len(english)} (например «{'», «'.join(list(dict.fromkeys(english))[:4])}»). "
            "Английский оставляй только для терминов и названий библиотек, остальное пиши по-русски"
        )
    # калибровка 30.10.2026 (patterns.md, «Связность»): доля ≥45% при 8+ парах у людей в 0–6% текстов
    # (Habr, КиберЛенинка, Lenta, ИНИОН), в нейтральной прозе Claude в 5%, в документах Claude для автора в 27%
    prose = [] if slides is not None else prose_paragraphs(text)
    pairs, broken = unlinked_pairs(prose)
    if pairs >= 8 and len(broken) / pairs >= 0.45:
        ln, a, b = broken[0]
        flags.append(
            f"связность: {len(broken)} из {pairs} пар соседних предложений без видимой связи "
            f"({len(broken) * 100 // pairs}%, порог 45%), например у строки {ln}: «{a[-60:]}» → «{b[:60]}». "
            "Нет связки, отсылки или общего слова: допиши, как второе следует из первого"
        )
    # у людей ≥15% в 0–6% текстов вне науки; в КиберЛенинке 65% из-за мусора PDF, поэтому в science молчим
    full, nopred = verbless(prose)
    if genre != "science" and len(full) >= 10 and len(nopred) / len(full) >= 0.15:
        flags.append(
            f"предложения без сказуемого: {len(nopred)} из {len(full)} (например «{nopred[0][:60]}»). "
            "Перечень ярлыков не связан мыслью: допиши глагол"
        )
    rhythm_note = None
    if (
        slides is None
        and len(lengths) >= 5
        and words >= 80
        and sigma is not None
        and sigma < 4
    ):
        rhythm_note = f"ритм ровный: σ длины предложения {sigma:.1f}. Справочно, в счёт не идёт: порог взят из практики, на русском не калиброван."
    # замер research/compare_model.py, 21.09.2026: в нейтральной прозе Claude (haiku, sonnet) предложений
    # короче 8 слов 0–5%, у людей на Habr медиана 31%; порог 5% флагует 63% модельных техстатей и 4%
    # человеческих. В новостях разделяет слабо (50% против 33%), там молчим.
    short = sum(1 for n in lengths if n < 8)
    if slides is None and genre != "news" and len(lengths) >= 12 and short / len(lengths) <= 0.05:
        flags.append(
            f"нет коротких предложений: {short} из {len(lengths)} короче 8 слов "
            "(у людей в техстатьях около трети; у модели 0–5%)"
        )
    # Решение автора 21.11.2026: в своём тексте тире нет, в чужом (--foreign) не больше одного на 200 слов. Это правило стиля, а не признак
    # модели: у людей на Habr p90 2,04 на 100 слов, и флаг ловит большую часть человеческих текстов (patterns.md, раздел 10).
    if dashes > dash_allowance(words, foreign):
        flags.append(
            f"тире: {dashes} на {words} слов, можно {dash_allowance(words, foreign)}. "
            "Замени запятой, точкой или скобками либо перестрой фразу с глаголом. Двоеточием не заменяй"
        )
    # Как и тире, это правило стиля: порог превышают 19% постов людей и 65–75% постов по памятке (colon_allowance).
    colons = [] if slides is not None else mid_colons(sents)
    if len(colons) > colon_allowance(words, foreign):
        flags.append(
            f"двоеточие в середине фразы: {len(colons)} на {words} слов, можно {colon_allowance(words, foreign)} "
            f"(например «{colons[0][:70]}»). Причину присоединяй союзом («потому что», «поэтому») или начни "
            "новое предложение. Строки записки «Тема: что решили» не трогай"
        )
    runs =[] if slides is not None else staccato_runs(sents)
    if runs:
        flags.append(
            f"рваные цепочки обрывков по 1–3 слова: {len(runs)} (длиннейшая {max(runs)})"
        )
    if per100(nominal) > 2.5:
        flags.append(
            f"отглагольные существительные: {nominal} ({per100(nominal):.1f} на 100 слов, порог 2.5)"
        )
    if slides is None and lines and items >= 4 and items / len(lines) > 0.5:
        flags.append(f"листикл: {items} пунктов, {items * 100 // len(lines)}% строк")
    colon_items = sum(1 for ln in lines if COLON_ITEM.match(ln))
    if colon_items >= 2:
        flags.append(f"пункты вида «**Заголовок:** …»: {colon_items}")
    title_heads = sum(1 for ln in lines if TITLE_HEAD.match(ln))
    if title_heads:
        flags.append(f"заголовки с заглавной каждого слова: {title_heads}")
    emoji_heads = sum(1 for ln in lines if EMOJI_HEAD.match(ln))
    if emoji_heads >= 2:
        flags.append(f"эмодзи в начале строк/заголовков: {emoji_heads}")
    if slides is None:
        fences = sum(1 for ln in raw.split("\n") if FENCE.match(ln))
        flags.extend(
            layout_flags(text, words, reference=genre == "tech" or fences >= 4, markup=getattr(raw, "layout", None))
        )

    hard = sum(1 for h in hits if h["cat"] in ("чатбот", "антитеза", "атрибуция"))
    soft = len(hits) - hard
    score = 100
    score -= min(40, 12 * sum(1 for h in hits if h["cat"] == "чатбот"))
    score -= min(20, 4 * sum(1 for h in hits if h["cat"] in ("антитеза", "атрибуция")))
    score -= min(30, round(3 * per100(soft)))
    score -= min(15, 5 * len(clusters))
    score -= min(8, 2 * len(flags))
    score = max(0, score)

    notes = []
    if rhythm_note:
        notes.append(rhythm_note)
    presence = len(PRESENCE.findall(text))
    if (
        slides is None
        and genre is None
        and words >= 300
        and presence / words * 1000 < 2
    ):
        notes.append(
            f"стерильно: хеджей и усилителей {presence} на {words} слов. У instruct-моделей их 40–67% от человеческой частоты "
            "(Reinhart et al., arXiv 2410.16107, английский корпус): не вычищать «возможно», «очень», «кажется», если они авторские."
        )
    if not hits and not flags and words >= 150:
        notes.append(
            "Маркеров нет. Так пишут не все живые авторы, но погоня за нулём даёт стерильный текст: дальше чистить незачем."
        )
    if words < 80:
        notes.append("Меньше 80 слов: метрики ритма и кластеры ненадёжны.")

    return {
        "words": words,
        "sentences": len(lengths),
        "sigma": None if sigma is None else round(sigma, 1),
        "markers": hits,
        "clusters": clusters,
        "flags": flags,
        "score": score,
        "notes": notes,
    }


def facts(raw):
    text = mask_foreign(raw)
    nums = {
        re.sub(r"\s|,", lambda m: "." if m.group(0) == "," else "", n)
        for n in NUMBER.findall(text)
    }
    names = {n.lower()[:5] for n in NAME.findall(text)}
    return nums, names


def fact_check(before, after):
    """Механическая страховка: числа и имена из «до» должны остаться в «после»."""
    bn, bnames = facts(before)
    an, anames = facts(after)
    lost_n = sorted(bn - an)
    lost_names = sorted(bnames - anames)
    wb, wa = (
        len(WORD.findall(mask_foreign(before))),
        len(WORD.findall(mask_foreign(after))),
    )
    shrink = (wb - wa) / wb * 100 if wb else 0.0
    out = []
    if lost_n:
        out.append("пропали числа: " + ", ".join(lost_n))
    if lost_names:
        out.append(
            "пропали имена/названия (по первым 5 буквам): " + ", ".join(lost_names)
        )
    if shrink > 25:
        out.append(f"текст сжат на {shrink:.0f}%: проверить, не потеряны ли факты")
    return out


_DASH_ADVERBS = frozenset("слева справа сверху снизу здесь там тут сегодня завтра вчера сейчас теперь потом".split())
_DASH_PREPS = frozenset("по на за до от из для при под над без про через около в во к ко с со у о об и а но или".split())


def dropped_dashes(before, after):
    """Тире из «до», которое в «после» стёрли, не перестроив фразу: слова по обе его стороны стоят подряд.

    Без исходника стёртое тире регуляркой не отличить от обычной фразы без глагола, поэтому проверка есть только в --compare.
    """
    out = []
    for m in re.finditer(r"([^\W\d_]{2,})[»\")]*[ \t]+[—–][ \t]+[«\"(]*([^\W\d_]{2,})", before):
        # «слева испорченное, справа оригинал» и «учителям по 12 тысяч, остальным по шесть» без тире читаются нормально
        if m.group(1).lower() in _DASH_ADVERBS or m.group(2).lower() in _DASH_PREPS:
            continue
        hit = re.search(
            rf"\b{re.escape(m.group(1))}[»\")]*[ \t]+[«\"(]*{re.escape(m.group(2))}\b", after
        )
        if hit and hit.group(0) not in out:
            out.append(hit.group(0))
    return out


